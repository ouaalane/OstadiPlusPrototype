#!/usr/bin/env node
/**
 * Copy `media/generated/*` into every application that ships media.
 *
 *  • teacher dashboard  → apps/teacher-dashboard/public/media   (served as /media/…)
 *  • student app        → apps/student-app/src/assets           (bundled via require())
 *
 * For the student app it also writes `src/assets/registry.ts`, the only place
 * that maps a demo file name to a bundled asset id — Metro needs literal
 * `require()` calls, so it has to be generated.
 *
 * Targets that do not exist yet are skipped with a message, so the script is
 * safe to run before an application has been scaffolded.
 */

import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const GEN = path.join(ROOT, 'media', 'generated');
const APP_ASSETS = path.join(ROOT, 'apps', 'student-app', 'src', 'assets');
const REGISTRY = path.join(APP_ASSETS, 'registry.ts');

const DASHBOARD = path.join(ROOT, 'apps', 'teacher-dashboard', 'public', 'media');

async function exists(dir) {
  try {
    await fs.access(dir);
    return true;
  } catch {
    return false;
  }
}

async function copyFolder(from, to) {
  await fs.mkdir(to, { recursive: true });
  const entries = await fs.readdir(from);
  for (const entry of entries) {
    await fs.copyFile(path.join(from, entry), path.join(to, entry));
  }
  return entries.filter((e) => !e.startsWith('.'));
}

function sortNames(names) {
  return [...names].sort((a, b) => a.localeCompare(b, 'en'));
}

async function main() {
  let total = 0;

  /* ---- teacher dashboard ---- */
  if (await exists(DASHBOARD)) {
    let count = 0;
    for (const folder of ['videos', 'posters', 'docs']) {
      const from = path.join(GEN, folder);
      if (!(await exists(from))) continue;
      count += (await copyFolder(from, path.join(DASHBOARD, folder))).length;
    }
    console.log(`sync  teacher dashboard (public/media) — ${count} files`);
    total += count;
  } else {
    console.log('skip  teacher dashboard (not scaffolded)');
  }

  /* ---- student app ---- */
  if (await exists(APP_ASSETS)) {
    const videos = await copyFolder(
      path.join(GEN, 'videos'),
      path.join(APP_ASSETS, 'videos'),
    );
    const posters = await copyFolder(
      path.join(GEN, 'posters'),
      path.join(APP_ASSETS, 'posters'),
    );
    const docPages = await copyFolder(
      path.join(GEN, 'doc-pages'),
      path.join(APP_ASSETS, 'doc-pages'),
    );

    /* group page images per document: limits-sheet-1.png → ['…-1', '…-2'] */
    const byDoc = new Map();
    for (const name of docPages) {
      const match = /^(.+)-(\d+)\.png$/.exec(name);
      if (!match) continue;
      const [, key, page] = match;
      if (!byDoc.has(key)) byDoc.set(key, []);
      byDoc.get(key).push({ page: Number(page), name });
    }

    const lines = [
      '/* eslint-disable */',
      '// @generated by scripts/sync-media.mjs — do not edit by hand.',
      '',
      '/** Video file name → bundled asset id. */',
      'export const videoAssets: Record<string, number> = {',
      ...sortNames(videos).map((f) => `  '${f}': require('./videos/${f}'),`),
      '};',
      '',
      '/** Video poster (jpg) file name → bundled asset id. */',
      'export const posterAssets: Record<string, number> = {',
      ...sortNames(posters).map((f) => `  '${f}': require('./posters/${f}'),`),
      '};',
      '',
      '/** PDF file name → page images, in reading order. */',
      'export const docPageAssets: Record<string, number[]> = {',
      ...sortNames([...byDoc.keys()]).map((key) => {
        const pages = byDoc
          .get(key)
          .sort((a, b) => a.page - b.page)
          .map((p) => `require('./doc-pages/${p.name}')`);
        return `  '${key}.pdf': [${pages.join(', ')}],`;
      }),
      '};',
      '',
    ];
    await fs.writeFile(REGISTRY, `${lines.join('\n')}\n`, 'utf8');
    console.log(
      `sync  student app (src/assets) — ${videos.length + posters.length + docPages.length} files + registry.ts`,
    );
    total += videos.length + posters.length + docPages.length;
  } else {
    console.log('skip  student app (not scaffolded)');
  }

  console.log(`media synchronised (${total} files)`);
}

main().catch((error) => {
  console.error(error);
  process.exit(1);
});
