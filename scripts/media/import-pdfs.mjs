#!/usr/bin/env node
/**
 * Import the real course documents (PDF) that sit in `media/source/alloschool/`
 * into the media pipeline.
 *
 * The Android app ships no PDF engine, so — exactly like the generated demo
 * documents — every page is rasterised to a PNG and bundled through
 * `src/assets/registry.ts`. This script is the real-document counterpart of the
 * HTML→PDF→PNG step in `generate-media.mjs`.
 *
 * For each document listed in `documents.json` it:
 *   1. copies `<key>.pdf`            → `media/generated/docs/<key>.pdf`
 *   2. rasterises every page         → `media/generated/doc-pages/<key>-<n>.png`
 *   3. returns the manifest entry    → `{ file, title, pages, sizeMb }`
 *
 * Standalone (`npm run media:pdfs`) it also merges those entries into
 * `packages/shared/src/media-manifest.json` and runs `sync-media.mjs`.
 *
 * Source: AlloSchool (https://www.alloschool.com) — 2ème Bac SPC-SVT.
 */

import { spawnSync } from 'node:child_process';
import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

import { pdf } from 'pdf-to-img';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', '..');
const SOURCE = path.join(ROOT, 'media', 'source', 'alloschool');
const GEN = path.join(ROOT, 'media', 'generated');
const DOC_DIR = path.join(GEN, 'docs');
const DOC_PAGES = path.join(GEN, 'doc-pages');
const MANIFEST = path.join(ROOT, 'packages', 'shared', 'src', 'media-manifest.json');

/** 72 dpi × 2 ≈ 150 dpi — sharp enough to zoom, still small enough to bundle. */
const SCALE = 2;

/** Reads `media/source/alloschool/documents.json`. */
export async function loadRealDocSources() {
  try {
    const raw = await fs.readFile(path.join(SOURCE, 'documents.json'), 'utf8');
    return JSON.parse(raw).documents ?? {};
  } catch (error) {
    if (error.code === 'ENOENT') return {};
    throw error;
  }
}

/** Keys handled by real PDFs — `generate-media.mjs` skips its demo versions. */
export async function realDocKeys() {
  return new Set(Object.keys(await loadRealDocSources()));
}

async function clearPages(key) {
  const prefix = `${key}-`;
  for (const name of await fs.readdir(DOC_PAGES)) {
    if (name.startsWith(prefix) && name.endsWith('.png')) {
      await fs.rm(path.join(DOC_PAGES, name), { force: true });
    }
  }
}

/**
 * Rasterise every real document. Returns the manifest entries keyed by
 * document key. Assumes `media/generated/{docs,doc-pages}` already exist.
 */
export async function importRealPdfs({ log = () => {} } = {}) {
  const sources = await loadRealDocSources();
  const keys = Object.keys(sources);
  if (keys.length === 0) return {};

  await fs.mkdir(DOC_DIR, { recursive: true });
  await fs.mkdir(DOC_PAGES, { recursive: true });

  const manifest = {};

  for (const key of keys) {
    const from = path.join(SOURCE, `${key}.pdf`);
    const to = path.join(DOC_DIR, `${key}.pdf`);
    await fs.copyFile(from, to);
    await clearPages(key);

    const document = await pdf(from, { scale: SCALE });
    let page = 0;
    for await (const image of document) {
      page += 1;
      await fs.writeFile(path.join(DOC_PAGES, `${key}-${page}.png`), image);
    }

    const { size } = await fs.stat(to);
    const sizeMb = Number((size / (1024 * 1024)).toFixed(1));
    manifest[key] = {
      file: `${key}.pdf`,
      title: sources[key].title,
      pages: page,
      sizeMb,
    };

    log(`  imported ${key} — ${page} pages, ${sizeMb} MB`);
  }

  return manifest;
}

async function main() {
  const started = Date.now();
  const imported = await importRealPdfs({ log: console.log });

  if (Object.keys(imported).length === 0) {
    console.log('nothing to import (media/source/alloschool is empty)');
    return;
  }

  const manifest = JSON.parse(await fs.readFile(MANIFEST, 'utf8'));
  manifest.pdfs = { ...manifest.pdfs, ...imported };
  manifest.note = 'Generated by `npm run media`. Never edit by hand.';
  await fs.writeFile(MANIFEST, `${JSON.stringify(manifest, null, 2)}\n`, 'utf8');
  console.log(`wrote ${path.relative(ROOT, MANIFEST)}`);

  const sync = spawnSync(process.execPath, [path.join(ROOT, 'scripts', 'sync-media.mjs')], {
    stdio: 'inherit',
  });
  if (sync.status !== 0) process.exit(sync.status ?? 1);

  console.log(`done in ${((Date.now() - started) / 1000).toFixed(1)}s`);
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  main().catch((error) => {
    console.error(error);
    process.exit(1);
  });
}
